/// หมวดของรายการ patch note
enum NoteKind { added, improved, fixed }

class ReleaseNote {
  const ReleaseNote({
    required this.version,
    required this.codename,
    required this.date,
    this.added = const [],
    this.improved = const [],
    this.fixed = const [],
  });

  final String version;
  final String codename;

  /// วันที่ปล่อย (ISO: 2026-11-04)
  final String date;

